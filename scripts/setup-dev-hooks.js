#!/usr/bin/env node
// Installer for repo-managed git hooks that enforce no dev citations before commit/push.
// Run: npm run setup:dev-hooks
// Writes .git/hooks/pre-commit and pre-push (executable) that call the verify script.
// These run the check on every commit/push. Remove markers first (temporary).

import { chmodSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = process.cwd();
const hooksDir = resolve(root, '.git/hooks');
if (!existsSync(hooksDir)) {
  console.error('No .git/hooks dir. Are you in a git repo?');
  process.exit(1);
}

const verify = resolve(root, 'scripts/verify-no-dev-citations.js');
const preCommit = resolve(hooksDir, 'pre-commit');
const prePush = resolve(hooksDir, 'pre-push');

const hookContent = (name) => `#!/bin/sh
# Auto-generated by scripts/setup-dev-hooks.js. Do not edit.
# Enforces dev citation cleanup before ${name}.
node "${verify}" || exit 1
`;

writeFileSync(preCommit, hookContent('commit'));
chmodSync(preCommit, 0o755);
writeFileSync(prePush, hookContent('push'));
chmodSync(prePush, 0o755);

console.log('Installed .git/hooks/pre-commit and pre-push for citation enforcement.');
console.log('They will block if VITE_MASTHEAD_DEV_CITATIONS=1 or data-ui-cite markers remain.');
console.log('During visual work: add markers + set flag in dev. Remove markers before commit (hooks enforce).');